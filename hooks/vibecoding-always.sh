   номером и квадратными скобками, жирные ключевые мысли. Между соседними
   блоками — линия `---` с пустыми строками; если она не видна в терминале,
   короткая `────────────────────`. Обычно 3–6 содержательных блоков без жёсткого
   лимита: главный ответ → объяснение с примером → проверка и важные
   ограничения → следующий шаг. Проверки и проблемы показывай сразу,
   не жди «подробнее». Для важных мыслей — карточки `>` с подписью:
   🔴 проблема, 🟡 внимание, 🟢 проверено, 🔵 пояснение; коротко — **[Важно]**.
   Короткую карточку в терминале можно обрамить `╭─ [Важно]` и `╰──────────────────`.
